"""Gazebo SDF + OBJ meshes for the twin wing, generated from the shared spec.

The Gazebo model is a *kinematic visual*: it is static and posed every tick
from the Aerial Kit plant's Telemetry by ``gazebo_fixedwing_pose_node``. It
uses exactly the same procedural parts as the MuJoCo model
(:class:`TwinWingGeometry`), with elevons at neutral and props at a fixed
angle. Gazebo does not solve the aerodynamics here.

Use ``scripts/generate_twin_wing_assets.py`` to write the files; its
``--check`` mode (run by the ROS asset tests) fails if the checked-in files
differ from what the YAML would produce.
"""

from __future__ import annotations

import math

import numpy as np

from .geometry import Mesh, TwinWingGeometry, VisualPart
from .spec import TwinWingSpec

MODEL_NAME = "twin_wing"
MESH_DIR = "meshes"


def _corner_normals(mesh: Mesh, crease_deg: float = 40.0) -> tuple[np.ndarray, np.ndarray]:
    """Crease-aware normals: smooth across shallow edges, split at sharp ones.

    Returns (normals, corner_normal_index) where corner index has the faces' shape.
    """
    fn = mesh.face_normals()
    lengths = np.linalg.norm(fn, axis=1, keepdims=True)
    unit = fn / np.maximum(lengths, 1e-15)
    cos_limit = math.cos(math.radians(crease_deg))
    incident: dict[int, list[int]] = {}
    for f, tri in enumerate(mesh.faces):
        for v in tri:
            incident.setdefault(int(v), []).append(f)
    normals: list[tuple[float, float, float]] = []
    lookup: dict[tuple[float, float, float], int] = {}
    corner = np.zeros_like(mesh.faces)
    for f, tri in enumerate(mesh.faces):
        for k, v in enumerate(tri):
            acc = np.zeros(3)
            for g in incident[int(v)]:
                if float(unit[f] @ unit[g]) >= cos_limit:
                    acc += fn[g]
            n = acc / max(float(np.linalg.norm(acc)), 1e-15)
            key = (round(float(n[0]), 4), round(float(n[1]), 4), round(float(n[2]), 4))
            if key not in lookup:
                lookup[key] = len(normals)
                normals.append(key)
            corner[f, k] = lookup[key]
    return np.asarray(normals, dtype=float), corner


MTL_NAME = "twin_wing.mtl"


def materials_mtl(spec: TwinWingSpec) -> str:
    lines = ["# Generated by aerial_kit.airframes.twin_wing.sdf -- do not edit."]
    for name, rgba in spec.materials.items():
        r, g, b, a = (float(x) for x in rgba)
        lines += [
            f"newmtl {name}",
            f"Ka {r * 0.55:.3f} {g * 0.55:.3f} {b * 0.55:.3f}",
            f"Kd {r:.3f} {g:.3f} {b:.3f}",
            "Ks 0.250 0.250 0.250",
            "Ns 40",
            f"d {a:.3f}",
            "",
        ]
    return "\n".join(lines)


def mesh_to_obj(name: str, mesh: Mesh, material: str | None = None) -> str:
    normals, corner = _corner_normals(mesh)
    lines = [
        "# Generated by aerial_kit.airframes.twin_wing.sdf -- do not edit.",
        f"mtllib {MTL_NAME}",
        f"o {name}",
    ]
    if material:
        lines.append(f"usemtl {material}")
    lines += [f"v {x:.5f} {y:.5f} {z:.5f}" for x, y, z in mesh.vertices]
    lines += [f"vn {x:.4f} {y:.4f} {z:.4f}" for x, y, z in normals]
    for tri, cn in zip(mesh.faces, corner):
        lines.append("f " + " ".join(f"{int(v) + 1}//{int(n) + 1}" for v, n in zip(tri, cn)))
    return "\n".join(lines) + "\n"


def _rgba(v, scale: float = 1.0) -> str:
    r, g, b, a = (float(x) for x in v)
    return f"{r * scale:.3f} {g * scale:.3f} {b * scale:.3f} {a:.3f}"


def _visual(part: VisualPart, origin: np.ndarray, rgba) -> str:
    x, y, z = (float(c) for c in origin)
    return f"""\
      <visual name="{part.name}">
        <pose>{x:.5f} {y:.5f} {z:.5f} 0 0 0</pose>
        <geometry>
          <mesh>
            <uri>model://twin_wing_visual/{MESH_DIR}/{part.name}.obj</uri>
          </mesh>
        </geometry>
        <material>
          <ambient>{_rgba(rgba, 0.55)}</ambient>
          <diffuse>{_rgba(rgba)}</diffuse>
          <specular>0.25 0.25 0.25 1</specular>
        </material>
      </visual>"""


def twin_wing_gazebo_files(spec: TwinWingSpec) -> dict[str, str]:
    """Relative path -> file content for the whole Gazebo model directory."""
    geo = TwinWingGeometry(spec)
    parts = geo.parts()
    files: dict[str, str] = {}
    visuals = []
    for part in parts:
        files[f"{MESH_DIR}/{part.name}.obj"] = mesh_to_obj(part.name, part.mesh, part.material)
        visuals.append(_visual(part, geo.body_origin(part.body), spec.materials[part.material]))
    files[f"{MESH_DIR}/{MTL_NAME}"] = materials_mtl(spec)
    files["model.sdf"] = f"""\
<?xml version="1.0"?>
<sdf version="1.8">
  <!--
    GENERATED from aerial_kit/airframes/twin_wing/twin_wing.yaml by
    scripts/generate_twin_wing_assets.py. Edit the YAML and regenerate;
    the script's check mode (run by the ROS asset tests) fails on drift.

    This asset is deliberately kinematic. The authoritative flight model is
    aerial_kit.dynamics.fixed_wing (analytic or MuJoCo-integrated), and
    gazebo_fixedwing_pose_node drives this model from that plant's Telemetry.
    Gazebo supplies the scene, camera and visual review; it is not claimed to
    be the aerodynamic solver here. Elevons are shown at neutral and props
    are static: articulation is only simulated in MuJoCo.

    Geometry uses body FRD coordinates (x forward, y right, z down), matching
    the quaternion published by the Aerial Kit plant. Parts are the same
    procedural meshes the MuJoCo model uses.
  -->
  <model name="{MODEL_NAME}">
    <static>true</static>
    <link name="body">
{chr(10).join(visuals)}
    </link>
  </model>
</sdf>
"""
    files["model.config"] = """\
<?xml version="1.0"?>
<model>
  <name>Twin Wing Visual</name>
  <version>2.0</version>
  <sdf version="1.8">model.sdf</sdf>
  <author>
    <name>Aerial Kit</name>
  </author>
  <description>
    Twin-motor flying-wing visual used by the Aerial Kit Gazebo twin.
    Generated from aerial_kit/airframes/twin_wing/twin_wing.yaml; the same
    procedural geometry as the MuJoCo model. Kinematic, pose-driven.
  </description>
</model>
"""
    return files
