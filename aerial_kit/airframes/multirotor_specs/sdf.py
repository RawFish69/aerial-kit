"""Gazebo SDF + OBJ assets generated from a shared multirotor spec.

The Gazebo asset is a kinematic visual. The MuJoCo plant remains the
authoritative dynamics source; ``gazebo_multirotor_pose_node`` moves this
static model from the plant's ``/uav/backend/odom`` stream.

Frame is body FLU (x forward, y left, z up), matching the spec, MuJoCo model
and ROS odometry. Root parts live on ``body``; rotor-local parts live on one
static link positioned at each rotor origin.
"""

from __future__ import annotations

import math
from pathlib import Path

import numpy as np

from aerial_kit.airframes.twin_wing.sdf import materials_mtl, mesh_to_obj

from .geometry import MultirotorGeometry, VisualPart, rotor_body
from .spec import MultirotorSpec

MESH_DIR = "meshes"


def _f(value: float) -> str:
    return f"{float(value):.9g}"


def _vec(values) -> str:
    return " ".join(_f(value) for value in np.asarray(values, dtype=float).ravel())


def _rgba(values, scale: float = 1.0) -> str:
    r, g, b, a = (float(value) for value in values)
    return f"{r * scale:.3f} {g * scale:.3f} {b * scale:.3f} {a:.3f}"


def _rpy(rotation: np.ndarray) -> np.ndarray:
    """Roll, pitch, yaw for an SDF XYZ rotation matrix."""
    r = np.asarray(rotation, dtype=float).reshape(3, 3)
    pitch = math.asin(float(np.clip(-r[2, 0], -1.0, 1.0)))
    if abs(math.cos(pitch)) > 1e-9:
        roll = math.atan2(float(r[2, 1]), float(r[2, 2]))
        yaw = math.atan2(float(r[1, 0]), float(r[0, 0]))
    else:
        roll = math.atan2(float(-r[1, 2]), float(r[1, 1]))
        yaw = 0.0
    return np.array([roll, pitch, yaw], dtype=float)


def _cad_model_uri(spec: MultirotorSpec, path: str | Path) -> str:
    """Resolve a CAD mesh to a model:// URI without copying the mesh."""
    if spec._cad is None:
        raise ValueError("CAD mesh URI requested for a procedural airframe")
    models_root = spec._cad.mesh_dir.parents[1]
    relative = Path(path).resolve().relative_to(models_root)
    return f"model://{relative.as_posix()}"


def _visual(
    spec: MultirotorSpec,
    part: VisualPart,
    model_name: str,
) -> str:
    material = spec.materials[part.material]
    if part.file is None:
        if part.mesh is None:
            raise ValueError(f"visual part {part.name!r} has neither mesh nor file")
        pose = "0 0 0 0 0 0"
        geometry = f"""\
          <mesh>
            <uri>model://{model_name}/{MESH_DIR}/{part.name}.obj</uri>
          </mesh>"""
    else:
        pose = _vec(np.concatenate((part.file.pos, _rpy(part.file.rot))))
        if part.file.scale == 1.0:
            scale = ""
        else:
            scale = f"\n            <scale>{_vec([part.file.scale] * 3)}</scale>"
        geometry = f"""\
          <mesh>
            <uri>{_cad_model_uri(spec, part.file.path)}</uri>{scale}
          </mesh>"""

    return f"""\
        <visual name="{part.name}">
          <pose>{pose}</pose>
          <geometry>
{geometry}
          </geometry>
          <material>
            <ambient>{_rgba(material, 0.55)}</ambient>
            <diffuse>{_rgba(material)}</diffuse>
            <specular>0.25 0.25 0.25 1</specular>
          </material>
        </visual>"""


def _generated_obj(part: VisualPart, mtl_name: str) -> str:
    if part.mesh is None:
        raise ValueError(f"procedural part {part.name!r} has no mesh")
    text = mesh_to_obj(part.name, part.mesh, part.material)
    text = text.replace(
        "# Generated by aerial_kit.airframes.twin_wing.sdf -- do not edit.",
        "# Generated by aerial_kit.airframes.multirotor_specs.sdf -- do not edit.",
    )
    first, rest = text.split("\n", 1)
    lines = rest.splitlines()
    lines[0] = f"mtllib {mtl_name}"
    return first + "\n" + "\n".join(lines) + "\n"


def _generated_mtl(spec: MultirotorSpec) -> str:
    return materials_mtl(spec).replace(
        "# Generated by aerial_kit.airframes.twin_wing.sdf -- do not edit.",
        "# Generated by aerial_kit.airframes.multirotor_specs.sdf -- do not edit.",
        1,
    )


def multirotor_gazebo_files(spec: MultirotorSpec) -> dict[str, str]:
    """Relative path -> content for one generated Gazebo model directory."""
    geometry = MultirotorGeometry(spec)
    parts = geometry.parts()
    model_name = f"{spec.name}_visual"
    mtl_name = f"{spec.name}.mtl"

    links: dict[str, list[VisualPart]] = {"body": []}
    for rotor in spec.rotors:
        links[rotor_body(rotor)] = []
    for part in parts:
        if part.body not in links:
            raise ValueError(
                f"part {part.name!r} references unknown body {part.body!r}")
        links[part.body].append(part)

    files: dict[str, str] = {}
    link_xml: list[str] = []
    for link_name, link_parts in links.items():
        origin = geometry.body_origin(link_name)
        visuals = "\n".join(
            _visual(spec, part, model_name)
            for part in link_parts
        )
        pose = f"      <pose>{_vec(origin)} 0 0 0</pose>\n" if np.any(origin) else ""
        link_xml.append(f"""\
    <link name="{link_name}">
{pose}{visuals}
    </link>""")
        for part in link_parts:
            if part.file is None:
                files[f"{MESH_DIR}/{part.name}.obj"] = _generated_obj(part, mtl_name)
    files[f"{MESH_DIR}/{mtl_name}"] = _generated_mtl(spec)

    title = spec.name.replace("_", " ").title()
    files["model.sdf"] = f"""\
<?xml version="1.0"?>
<sdf version="1.8">
  <!--
    GENERATED from {spec.source} by scripts/generate_multirotor_assets.py.
    Edit the YAML and regenerate; check mode fails on drift.

    Kinematic visual only. gazebo_multirotor_pose_node drives this static
    model from /uav/backend/odom; the MuJoCo multirotor plant remains the
    authoritative dynamics. Body frame is FLU; procedural rotor parts and CAD
    prop meshes are positioned at their rotor origins.
  -->
  <model name="{spec.name}">
    <static>true</static>
{chr(10).join(link_xml)}
  </model>
</sdf>
"""
    files["model.config"] = f"""\
<?xml version="1.0"?>
<model>
  <name>{title} Visual</name>
  <version>1.0</version>
  <sdf version="1.8">model.sdf</sdf>
  <author>
    <name>Aerial Kit</name>
  </author>
  <description>
    Kinematic Gazebo visual for the Aerial Kit multirotor {spec.name}.
    Generated from {spec.source}; posed from /uav/backend/odom.
  </description>
</model>
"""
    return files
